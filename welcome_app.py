import streamlit as st

# إعدادات الصفحة
st.set_page_config(
    page_title="هندسة الجسد",
    page_icon="🧠",
    layout="wide"
)

# القائمة الجانبية
st.sidebar.title("🗺️ أجهزة الجسم")
option = st.sidebar.selectbox(
    "اختر جهازاً:",
    ["الرئيسية", "الجهاز الهضمي", "الجهاز الهيكلي", "الجهاز القلبي", "الجهاز التنفسي", "الجهاز العصبي"]
)

# المحتوى حسب الاختيار
if option == "الرئيسية":
    st.title("🧠 مرحباً بك في منصة **هندسة الجسد**")
    st.markdown("افهم جسدك كآلة محكمة، بمعلومات مبنية على حقائق علمية ثابتة.")
    st.info("اختر جهازاً من القائمة الجانبية (على اليسار) لبدء التعلم.")

elif option == "الجهاز الهضمي":
    st.title("🍽️ الجهاز الهضمي: مصنع معالجة الوقود")
    
    col1, col2 = st.columns(2)
    
    with col1:
        st.subheader("🧩 الأعضاء")
        organ = st.selectbox("اختر عضواً:", ["المعدة", "الأمعاء الدقيقة", "الكبد", "البنكرياس"])
        if organ == "المعدة":
            st.info("خلاط كيميائي حمضي (pH 1.5-2)، يهرس الطعام ويكسر البروتينات.")
        elif organ == "الأمعاء الدقيقة":
            st.info("طولها 6-7 أمتار، تمتص 90% من العناصر الغذائية.")
        elif organ == "الكبد":
            st.info("معمل كيميائي رئيسي، يقوم بأكثر من 500 وظيفة.")
        elif organ == "البنكرياس":
            st.info("يفرز الإنزيمات الهاضمة وهرموني الأنسولين والجلوكاجون.")
    
    with col2:
        st.subheader("⚙️ حقائق هندسية")
        st.write("🔹 المعدة تبطن بطبقة مخاطية تتجدد كل 3 أيام.")
        st.write("🔹 الأمعاء الدقيقة لو بسطت لغطت مساحة ملعب تنس.")
        st.write("🔹 الكبد هو العضو الوحيد القادر على تجديد نفسه بنسبة 70%.")
    
    st.subheader("📝 اختبار سريع")
    q = st.radio("أين يتم امتصاص معظم العناصر الغذائية؟", ["المعدة", "الأمعاء الدقيقة", "الأمعاء الغليظة"])
    if st.button("تحقق"):
        if q == "الأمعاء الدقيقة":
            st.success("✅ صحيح!")
        else:
            st.error("❌ حاول مرة أخرى.")

elif option == "الجهاز الهيكلي":
    st.title("🦴 الجهاز الهيكلي: الهيكل الداعم")
    st.info("سيتم إضافة محتوى تفاعلي للجهاز الهيكلي قريباً...")

elif option == "الجهاز القلبي":
    st.title("❤️ الجهاز القلبي: مضخة الحياة")
    st.info("سيتم إضافة محتوى تفاعلي للجهاز القلبي قريباً...")

elif option == "الجهاز التنفسي":
    st.title("🌬️ الجهاز التنفسي: تبادل الغازات")
    st.info("سيتم إضافة محتوى تفاعلي للجهاز التنفسي قريباً...")

elif option == "الجهاز العصبي":
    st.title("🧠 الجهاز العصبي: شبكة التحكم")
    st.info("سيتم إضافة محتوى تفاعلي للجهاز العصبي قريباً...")

st.sidebar.markdown("---")
st.sidebar.caption("مشروع هندسة الجسد | في تطوير مستمر")