import streamlit as st

# إعدادات الصفحة
st.set_page_config(
    page_title="الجهاز الهضمي - هندسة الجسد",
    page_icon="🍽️",
    layout="wide"
)

# العنوان الرئيسي
st.title("🍽️ الجهاز الهضمي: مصنع معالجة الوقود")
st.markdown("---")

# قسم المعلومات الأساسية
with st.expander("📖 نظرة عامة (اضغط للقراءة)"):
    st.markdown("""
    الجهاز الهضمي هو **مصنع كيميائي - ميكانيكي** يحول الطعام إلى وقود للجسم.
    
    **الأعضاء الرئيسية:**
    - الفم (الطحن والترطيب الأولي)
    - المريء (الناقل)
    - المعدة (خلاط حمضي)
    - الأمعاء الدقيقة (الامتصاص الرئيسي)
    - الكبد والبنكرياس (المعمل الكيميائي)
    - الأمعاء الغليظة (استعادة الماء)
    """)

# إنشاء ثلاث أعمدة للمحتوى
col1, col2, col3 = st.columns(3)

# العمود 1: أعضاء الجهاز
with col1:
    st.subheader("🧩 الأعضاء")
    organ = st.selectbox(
        "اختر عضواً لترى وظيفته:",
        ["المعدة", "الأمعاء الدقيقة", "الكبد", "البنكرياس", "الأمعاء الغليظة"]
    )
    
    if organ == "المعدة":
        st.info("**المعدة** 🌀\n\nخلاط كيميائي حمضي (pH 1.5-2)، تهرسه وتفكك البروتينات.")
    elif organ == "الأمعاء الدقيقة":
        st.info("**الأمعاء الدقيقة** 🧬\n\nحزام ناقل طوله 6-7 أمتار، يمتص 90% من العناصر الغذائية.")
    elif organ == "الكبد":
        st.info("**الكبد** 🏭\n\nمعمل كيميائي رئيسي، يقوم بأكثر من 500 وظيفة (تنقية، تخزين، تصنيع).")
    elif organ == "البنكرياس":
        st.info("**البنكرياس** 🧪\n\nيُفرز الإنزيمات الهاضمة وهرموني الأنسولين والجلوكاجون.")
    elif organ == "الأمعاء الغليظة":
        st.info("**الأمعاء الغليظة** 💧\n\nتمتص الماء والأملاح، وتحول الفضائل إلى براز صلب.")

# العمود 2: رحلة الطعام
with col2:
    st.subheader("🔄 رحلة الطعام")
    stage = st.slider("مرحلة الهضم:", 1, 5, 1)
    
    if stage == 1:
        st.success("**الفم** 🦷\nالطحن والمضغ + إنزيم الأميليز (بدء هضم النشويات)")
    elif stage == 2:
        st.success("**المعدة** 🌀\nالهرم والخلط مع الأحماض والإنزيمات")
    elif stage == 3:
        st.success("**الأمعاء الدقيقة** 🧬\nالامتصاص الرئيسي للعناصر الغذائية")
    elif stage == 4:
        st.success("**الأمعاء الغليظة** 💧\nامتصاص الماء وتكوين البراز")
    elif stage == 5:
        st.success("**الإخراج** 🚽\nالتخلص من الفضائل الصلبة")

# العمود 3: حقائق هندسية
with col3:
    st.subheader("⚙️ حقائق هندسية")
    facts = [
        "🔹 **المعدة** تبطن بطبقة مخاطية تتجدد كل 3 أيام (تصميم ذاتي الصيانة).",
        "🔹 **الأمعاء الدقيقة** لو بُسطت لغطت مساحة ملعب تنس (~260 م²).",
        "🔹 **الكبد** هو العضو الوحيد القادر على تجديد نفسه بنسبة تصل إلى 70%.",
        "🔹 **التمعج** (حركة الأمعاء) يعمل كموجات دفع، مثل عصر معجون الأسنان من الأنبوب."
    ]
    for fact in facts:
        st.write(fact)

# قسم إضافي: اختبار سريع
st.markdown("---")
st.subheader("📝 اختبار سريع: جهاز الهضم")

question = st.radio(
    "أين يتم امتصاص معظم العناصر الغذائية؟",
    ["المعدة", "الأمعاء الدقيقة", "الأمعاء الغليظة", "الكبد"]
)

if st.button("تحقق الإجابة"):
    if question == "الأمعاء الدقيقة":
        st.success("✅ إجابة صحيحة! الأمعاء الدقيقة هي موقع الامتصاص الرئيسي.")
    else:
        st.error("❌ إجابة غير صحيحة. الأمعاء الدقيقة هي المسؤولة عن امتصاص معظم العناصر الغذائية.")

# تذييل الصفحة
st.markdown("---")
st.caption("المحتوى مبني على حقائق علمية ثابتة | مشروع هندسة الجسد")